package com.kaabuydev.kaabuy.Services;

import com.kaabuydev.kaabuy.DTO.Authentication.StaffResponse;
import com.kaabuydev.kaabuy.DTO.Staff.PasswordChangeRequest;
import com.kaabuydev.kaabuy.DTO.Staff.ProfileUpdateRequest;
import com.kaabuydev.kaabuy.DTO.Staff.StaffRequest;
import com.kaabuydev.kaabuy.Exceptions.ResourceNotFoundException;
import com.kaabuydev.kaabuy.Models.Staff;
import com.kaabuydev.kaabuy.Repositories.StaffRepository;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;
import java.util.stream.Collectors;

@Service
@Transactional
public class StaffService {

    private final StaffRepository staffRepository;
    private final PasswordEncoder passwordEncoder;
    private final EmailService emailService;

    public StaffService(StaffRepository staffRepository, PasswordEncoder passwordEncoder, EmailService emailService) {
        this.staffRepository = staffRepository;
        this.passwordEncoder = passwordEncoder;
        this.emailService = emailService;
    }

    // Create new staff with auto-generated credentials
    public StaffResponse createStaff(StaffRequest request) {
        // Generate credentials if not provided
        String finalUsername = request.getUsername();
        String finalPassword = request.getPassword();
        boolean isAutoGenerated = false;

        if (finalUsername == null || finalUsername.isBlank()) {
            // Generate username: firstname.lastname + random 4 digits
            String base = (request.getFirstName() + "." + request.getLastName())
                    .toLowerCase().replaceAll("\\s+", "");
            finalUsername = base + (int) (Math.random() * 9000 + 1000);
            isAutoGenerated = true;
        }

        if (finalPassword == null || finalPassword.isBlank()) {
            // Generate random 8-char password
            finalPassword = java.util.UUID.randomUUID().toString().substring(0, 8);
            isAutoGenerated = true;
        }

        // Check if email already exists
        if (request.getEmail() != null && !request.getEmail().isBlank() &&
                staffRepository.findByEmailAndIsActiveTrue(request.getEmail()).isPresent()) {
            throw new RuntimeException("Email already exists");
        }

        // Check if username already exists
        if (staffRepository.findByUsernameAndIsActiveTrue(finalUsername).isPresent()) {
            // If auto-generated, retry with different suffix
            if (isAutoGenerated) {
                finalUsername = finalUsername + (int) (Math.random() * 9000 + 1000);
            } else {
                throw new RuntimeException("Username already exists");
            }
        }

        Staff staff = new Staff();
        staff.setUsername(finalUsername);
        staff.setPassword(passwordEncoder.encode(finalPassword));
        staff.setFirstName(request.getFirstName());
        staff.setLastName(request.getLastName());
        staff.setEmail(request.getEmail());
        staff.setStoreName(request.getStoreName());
        staff.setRole(request.getRole());
        staff.setActive(true);
        staff.setRequiresPasswordChange(isAutoGenerated); // Force change if auto-generated

        Staff savedStaff = staffRepository.save(staff);

        // Send email with credentials (or log to console if email fails)
        if (isAutoGenerated) {
            emailService.sendWelcomeEmail(savedStaff.getEmail(), finalUsername, finalPassword);
        }

        return mapToResponse(savedStaff);
    }

    // Get all ACTIVE staff only (Newest First)
    public List<StaffResponse> getAllStaff() {
        return staffRepository.findByIsActiveTrue() // ✅ Use repository method
                .stream()
                .sorted((s1, s2) -> s2.getStaffId().compareTo(s1.getStaffId())) // Sort by ID desc
                .map(this::mapToResponse)
                .collect(Collectors.toList());
    }

    // Get staff by ID
    public StaffResponse getStaffById(Integer staffId) {
        Staff staff = staffRepository.findById(staffId)
                .orElseThrow(() -> new ResourceNotFoundException("Staff", "staffId", staffId));
        return mapToResponse(staff);
    }

    // Update staff
    public StaffResponse updateStaff(Integer staffId, StaffRequest request) {
        Staff staff = staffRepository.findById(staffId)
                .orElseThrow(() -> new ResourceNotFoundException("Staff", "staffId", staffId));

        // ✅ CHANGED: Check if username exists among ACTIVE users (excluding current
        // staff)
        if (!staff.getUsername().equals(request.getUsername()) &&
                staffRepository.findByUsernameAndIsActiveTrue(request.getUsername()).isPresent()) {
            throw new RuntimeException("Username already exists");
        }

        staff.setUsername(request.getUsername());
        // Only update password if provided
        if (request.getPassword() != null && !request.getPassword().isEmpty()) {
            staff.setPassword(passwordEncoder.encode(request.getPassword()));
        }
        staff.setFirstName(request.getFirstName());
        staff.setLastName(request.getLastName());
        staff.setStoreName(request.getStoreName());
        staff.setRole(request.getRole());

        Staff updatedStaff = staffRepository.save(staff);
        return mapToResponse(updatedStaff);
    }

    // ✅ SOFT DELETE
    public void deleteStaff(Integer staffId) {
        Staff staff = staffRepository.findById(staffId)
                .orElseThrow(() -> new ResourceNotFoundException("Staff", "staffId", staffId));

        // ✅ Prevent self-deletion
        String currentUsername = SecurityContextHolder.getContext().getAuthentication().getName();
        if (staff.getUsername().equals(currentUsername)) {
            throw new RuntimeException("You cannot delete your own account");
        }

        staff.setActive(false);
        staffRepository.save(staff);
    }

    // Update profile (Self)
    public StaffResponse updateProfile(Integer staffId, ProfileUpdateRequest request) {
        Staff staff = staffRepository.findById(staffId)
                .orElseThrow(() -> new ResourceNotFoundException("Staff", "staffId", staffId));

        staff.setFirstName(request.getFirstName());
        staff.setLastName(request.getLastName());
        staff.setEmail(request.getEmail());
        if (request.getStoreName() != null) {
            staff.setStoreName(request.getStoreName());
        }

        Staff updatedStaff = staffRepository.save(staff);
        return mapToResponse(updatedStaff);
    }

    // Change password (Self)
    public void changePassword(Integer staffId, PasswordChangeRequest request) {
        Staff staff = staffRepository.findById(staffId)
                .orElseThrow(() -> new ResourceNotFoundException("Staff", "staffId", staffId));

        if (!passwordEncoder.matches(request.getOldPassword(), staff.getPassword())) {
            throw new RuntimeException("Invalid old password");
        }

        staff.setPassword(passwordEncoder.encode(request.getNewPassword()));
        staff.setRequiresPasswordChange(false);
        staffRepository.save(staff);
    }

    // Get ID by Username
    public Integer getStaffIdByUsername(String username) {
        return staffRepository.findByUsernameAndIsActiveTrue(username)
                .map(Staff::getStaffId)
                .orElseThrow(() -> new ResourceNotFoundException("Staff", "username", username));
    }

    // Helper method to map entity to response
    private StaffResponse mapToResponse(Staff staff) {
        return new StaffResponse(
                staff.getStaffId(),
                staff.getUsername(),
                staff.getFirstName(),
                staff.getLastName(),
                staff.getStoreName(),
                staff.getRole());
    }
}